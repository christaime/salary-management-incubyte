-- c000: FULL
-------------------------------------------------------------------------------
INSERT INTO tmp_ranked
SELECT
    'c000', s.payroll_period_id,
    s.assignment_country_id, s.assignment_department_id,
    s.assignment_role_id, s.assignment_employment_type, s.employee_id,
    s.total, s.currency,
    CASE WHEN s.currency = ref.code THEN s.total
         ELSE s.total * cr.reference_amount / cr.rate END,
    ref.code,
    CASE p.frequency WHEN 'MONTHLY' THEN 31 WHEN 'BI_WEEKLY' THEN 14 ELSE 0 END,
    CASE p.frequency
        WHEN 'MONTHLY'   THEN (CASE WHEN s.currency = ref.code THEN s.total
                                    ELSE s.total * cr.reference_amount / cr.rate END)
        WHEN 'BI_WEEKLY' THEN (CASE WHEN s.currency = ref.code THEN s.total
                                    ELSE s.total * cr.reference_amount / cr.rate END) / 14 * 31
        ELSE 0 END,
    ref.code,
    ROW_NUMBER() OVER (
        PARTITION BY s.payroll_period_id, s.assignment_country_id,
                     s.assignment_department_id, s.assignment_role_id,
                     s.assignment_employment_type
        ORDER BY (CASE p.frequency
                    WHEN 'MONTHLY'   THEN (CASE WHEN s.currency = ref.code THEN s.total
                                                ELSE s.total * cr.reference_amount / cr.rate END)
                    WHEN 'BI_WEEKLY' THEN (CASE WHEN s.currency = ref.code THEN s.total
                                                ELSE s.total * cr.reference_amount / cr.rate END) / 14 * 31
                    ELSE 0 END) DESC,
                 s.employee_id ASC),
    ROW_NUMBER() OVER (
        PARTITION BY s.payroll_period_id, s.assignment_country_id,
                     s.assignment_department_id, s.assignment_role_id,
                     s.assignment_employment_type
        ORDER BY (CASE p.frequency
                    WHEN 'MONTHLY'   THEN (CASE WHEN s.currency = ref.code THEN s.total
                                                ELSE s.total * cr.reference_amount / cr.rate END)
                    WHEN 'BI_WEEKLY' THEN (CASE WHEN s.currency = ref.code THEN s.total
                                                ELSE s.total * cr.reference_amount / cr.rate END) / 14 * 31
                    ELSE 0 END) ASC,
                 s.employee_id ASC),
    COUNT(*) OVER (
        PARTITION BY s.payroll_period_id, s.assignment_country_id,
                     s.assignment_department_id, s.assignment_role_id,
                     s.assignment_employment_type)
FROM payroll_summaries s
INNER JOIN payroll_periods p ON p.id = s.payroll_period_id
CROSS JOIN (SELECT reference_currency_code AS code FROM currency_rates LIMIT 1) ref
LEFT JOIN currency_rates cr
    ON cr.currency_code = s.currency AND cr.reference_currency_code = ref.code
WHERE s.status = 'VALIDATED'
  AND (s.currency = ref.code OR cr.rate IS NOT NULL);

