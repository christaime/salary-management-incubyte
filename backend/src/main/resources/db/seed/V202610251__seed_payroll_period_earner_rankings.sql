-- Seed: payroll period earner rankings + percentiles.
--
-- Ranked by monthly_rate_amount (normalized), NOT by raw reference_amount.
-- For a MONTHLY employee: monthly_rate_amount = reference_amount
-- For a BI_WEEKLY employee: monthly_rate_amount = reference_amount / 14 * 31
--
-- Partition kinds:
--   c000  FULL              (country, department, role, employment_type)
--   c001  COUNTRY           (country only)
--   c002  DEPARTMENT        (department only)
--   c003  ROLE              (role only)
--   c004  EMPLOYMENT_TYPE   (employment_type only)
--   c005  GLOBAL            (no dimension)
--
-- All ids are valid UUID strings: 8-4-4-4-12 hex digits, generated by printf,
-- never touched by integer arithmetic. The 4th group encodes kind+direction
-- (rankings) or kind+percentile-marker (percentiles); the 1st group is a
-- global ROW_NUMBER() that guarantees uniqueness.

-------------------------------------------------------------------------------
-- 0. Clean slate.
-------------------------------------------------------------------------------
DELETE FROM payroll_period_earner_percentiles;
DELETE FROM payroll_period_earner_rankings;
DROP TABLE IF EXISTS tmp_ranked;

CREATE TEMP TABLE tmp_ranked (
    partition_kind       TEXT NOT NULL,
    payroll_period_id    TEXT NOT NULL,
    country_id           TEXT,
    department_id        TEXT,
    role_id              TEXT,
    employment_type      TEXT,
    employee_id          TEXT NOT NULL,
    original_amount      NUMERIC(38, 2) NOT NULL,
    original_currency    TEXT NOT NULL,
    reference_amount     NUMERIC(38, 2) NOT NULL,
    reference_currency   TEXT NOT NULL,
    days_covered         INTEGER NOT NULL,
    monthly_rate_amount  NUMERIC(38, 2) NOT NULL,
    monthly_rate_currency TEXT NOT NULL,
    top_rank             INTEGER NOT NULL,
    bottom_rank          INTEGER NOT NULL,
    n                    INTEGER NOT NULL
);

